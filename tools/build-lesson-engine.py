"""Build dist/lesson-engine.js (window.GuroEngine) from the content sources in src/.

Run from the repository root:  python3 tools/build-lesson-engine.py
The engine looks up a DepEd competency by grade, learning area, term and row (as listed in
dist/gradeN-curriculum.js) and returns ready items, passages, activities and lesson-family text.
"""
import json, os
ORDER = '''math/skills.js math/competencies-g1-6.js math/lesson-families.js shared.js
english/generators.js english/item-banks.js english/passages.js english/tasks-and-lesson-families.js
english/terms1-2-word-banks.js english/terms1-2-grammar-references-forms.js english/competencies-g2-6.js
science/items-and-activities-g3-6-term3.js science/competencies-g3-6.js science-jhs/calculators.js
science/calculators-g3-6.js science/items-and-activities-g3-t1-2.js science/items-and-activities-g4-t1-2.js
science/items-and-activities-g5-t1-2.js science/items-and-activities-g6-t1-2.js
science-jhs/items-and-activities-g7.js science-jhs/items-and-activities-g8.js science-jhs/items-and-activities-g9.js
science-jhs/items-and-activities-g10.js science-jhs/extra-foundation-items.js science-jhs/competencies-g7-10.js
english-jhs/banks-literary.js english-jhs/banks-informational-letters.js english-jhs/banks-more-literary.js
english-jhs/banks-more-informational-letters.js english-jhs/tasks-skill-lesson-families.js english-jhs/competencies-g7-10.js'''.split()
JHS_MATH = '''math-jhs/helpers-and-number.js math-jhs/algebra-and-functions.js math-jhs/geometry-measurement-trig.js
math-jhs/data-probability-finance-banks.js math-jhs/register-and-lesson-families.js'''.split()
src = lambda p: open(os.path.join('src', p), encoding='utf-8').read() + '\n'
core = ''.join(src(p) for p in ORDER)
core += '{ /* JHS math: block scope */\n' + ''.join(src(p) for p in JHS_MATH) + '}\n' + src('math-jhs/competencies-g7-10.js')
rows = json.load(open('src/lesson-engine/elementary-math-rows.json'))
js = ('/* GuroPrep lesson engine: original items, passages, activities and lesson families for DepEd Mathematics, '
      'English and Science, Grades 1–10 (all terms). Generated by tools/build-lesson-engine.py; edit src/, not this file. */\n'
      'window.GuroEngine=(function(){\n"use strict";\nconst __MATHMAP=' + json.dumps(rows, separators=(',', ':')) + ';\n'
      + core + '\n' + src('lesson-engine/adapter.js') + '})();\n')
open('dist/lesson-engine.js', 'w', encoding='utf-8').write(js)
print('dist/lesson-engine.js', len(js), 'bytes')
